import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://localhost:5173/?new&t=0.4&at=-650,-590&yaw=1.3&pitch=0.1');
await page.waitForTimeout(5000);
await page.keyboard.press('KeyR');
await page.waitForTimeout(600);
await page.keyboard.type('Test report: the shelves look fine, this is only a test. were walking keys ignored?');
await page.screenshot({ path: 'shots/report_form.png' });
await page.keyboard.press('Control+Enter');
await page.waitForTimeout(1500);
const meta = await page.evaluate(() => document.getElementById('reportMeta').textContent);
console.log(meta, '| player moved while typing:', await page.evaluate(() => window.__game.player.pos.x.toFixed(1)), 'errors', errors.join(';') || 'none');
const id = meta.replace('saved as reports/', '');
await page.goto('http://localhost:5173/?report=' + id);
await page.waitForTimeout(5000);
await page.screenshot({ path: 'shots/report_replay.png' });
console.log('replayed at', await page.evaluate(() => { const g = window.__game; return g.player.pos.x.toFixed(1) + ',' + g.player.pos.z.toFixed(1) + ' yaw ' + g.rig.yaw.toFixed(2); }));
await browser.close();
